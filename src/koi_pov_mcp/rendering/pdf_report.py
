"""
PDF report.

povplatform renders its PDF with WeasyPrint from the HTML report. WeasyPrint
needs system GTK, which a plain Windows workstation does not have, so this
draws the same document with reportlab: pure Python, identical print palette,
same section order as the DOCX.

The analytical sections (supply chain, findings, attack scenarios,
recommended actions, threat context) live in pdf_sections.py; this file owns
the document, the palette and the formatting helpers, and hands them over.
"""

from __future__ import annotations

import logging
from pathlib import Path
from xml.sax.saxutils import escape as _escape

from . import pdf_sections
from .common import NOT_MEASURED, Data

log = logging.getLogger(__name__)


def esc(value) -> str:
    """reportlab parses paragraph text as markup, so & and < must be escaped
    before any of our own colour tags are added."""
    return _escape(str(value))


TEAL_DARK = "#0B6E4F"
TEAL = "#12805C"
AMBER = "#B45309"
RED = "#B91C1C"
GREY = "#5A6B62"
LIGHT = "#7A8B82"
RULE = "#C8D5CD"
ZEBRA = "#F1F6F3"

RISK_COLOUR = {
    "critical": RED,
    "high": AMBER,
    "medium": "#0D9488",
    "low": TEAL,
    "pending": GREY,
}

SECTION_PALETTE = {**RISK_COLOUR, "info": GREY, "muted": LIGHT}

VERDICT_COLOUR = {
    "met": TEAL_DARK,
    "passed": TEAL_DARK,
    "partially met": AMBER,
    "partial": AMBER,
    "not met": RED,
    "failed": RED,
    "not tested": GREY,
    "not measured": GREY,
}


def build_pdf(data: dict, out_path: str, narrative: dict | None = None) -> str:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
    )

    r = Data(data)
    n = narrative or {}
    base = getSampleStyleSheet()

    body = ParagraphStyle("body", parent=base["BodyText"], fontName="Helvetica",
                          fontSize=9.5, leading=13, spaceAfter=5)
    h1 = ParagraphStyle("h1", parent=base["Heading1"], fontName="Helvetica-Bold",
                        fontSize=16, leading=20, spaceBefore=14, spaceAfter=3,
                        textColor=colors.HexColor(TEAL_DARK))
    h2 = ParagraphStyle("h2", parent=base["Heading2"], fontName="Helvetica-Bold",
                        fontSize=11.5, leading=15, spaceBefore=10, spaceAfter=2,
                        textColor=colors.HexColor(TEAL))
    lede_st = ParagraphStyle("lede", parent=body, fontName="Helvetica-Oblique",
                             fontSize=9, textColor=colors.HexColor(GREY))
    note_st = ParagraphStyle("note", parent=body, fontName="Helvetica-Oblique",
                             fontSize=8, textColor=colors.HexColor(LIGHT))
    tag_st = ParagraphStyle("tag", parent=body, fontSize=7.5, leading=10,
                            spaceAfter=3)
    headline_st = ParagraphStyle("headline", parent=body, fontSize=12,
                                 leading=16, fontName="Helvetica-Bold",
                                 textColor=colors.HexColor(TEAL_DARK),
                                 spaceAfter=8)
    cell = ParagraphStyle("cell", parent=body, fontSize=8, leading=10.5,
                          spaceAfter=0)
    cell_head = ParagraphStyle("cellhead", parent=cell,
                               fontName="Helvetica-Bold",
                               textColor=colors.white)
    cover_title = ParagraphStyle("covert", parent=base["Title"],
                                 fontName="Helvetica-Bold", fontSize=30,
                                 textColor=colors.HexColor(TEAL_DARK),
                                 alignment=TA_CENTER, spaceAfter=6)
    cover_sub = ParagraphStyle("covers", parent=body, fontSize=14,
                               alignment=TA_CENTER,
                               textColor=colors.HexColor(TEAL), spaceAfter=18)
    cover_info = ParagraphStyle("coveri", parent=body, fontSize=11,
                                alignment=TA_CENTER,
                                textColor=colors.HexColor(GREY))

    doc = SimpleDocTemplate(
        str(out_path), pagesize=A4,
        leftMargin=17 * mm, rightMargin=17 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title="Cortex AES PoV \u2014 " + r.customer,
        author=str(r.meta.get("prepared_by") or ""),
    )
    width = doc.width
    story: list = []

    def para(text, style=body):
        for chunk in str(text).split("\n"):
            if chunk.strip():
                story.append(Paragraph(esc(chunk.strip()), style))

    def heading(text, level=1):
        story.append(Paragraph(esc(text), h1 if level == 1 else h2))

    def page_break():
        story.append(PageBreak())

    def tag_paragraph(markup: str):
        """Pre-built markup, already escaped by the caller where needed."""
        return Paragraph(markup, tag_st)

    def table(headers, rows, weights=None, colour_col=None, palette=None):
        if not rows:
            return
        head = [Paragraph(esc(h), cell_head) for h in headers]
        body_rows = []
        styles = [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(TEAL_DARK)),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor(RULE)),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1),
             [colors.white, colors.HexColor(ZEBRA)]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]
        for ri, row in enumerate(rows, start=1):
            cells = []
            for ci, value in enumerate(row):
                text = esc(value)
                if colour_col is not None and ci == colour_col:
                    hexcode = (palette or RISK_COLOUR).get(str(value).lower())
                    if hexcode:
                        text = ('<font color="' + hexcode + '"><b>' + text
                                + "</b></font>")
                cells.append(Paragraph(text, cell))
            body_rows.append(cells)
        if weights:
            total = float(sum(weights))
            col_widths = [width * (w / total) for w in weights]
        else:
            col_widths = [width / len(headers)] * len(headers)
        t = Table([head] + body_rows, colWidths=col_widths, repeatRows=1)
        t.setStyle(TableStyle(styles))
        story.append(t)
        story.append(Spacer(1, 7))

    kit = pdf_sections.Kit(
        story=story, para=para, table=table, page_break=page_break,
        h1=h1, h2=h2, body=body, lede=lede_st, note=note_st,
        heading=heading, tag_style=tag_paragraph, palette=SECTION_PALETTE,
    )

    # ---------------------------------------------------------------- cover
    story.append(Spacer(1, 60 * mm))
    story.append(Paragraph("Cortex AES", cover_title))
    story.append(Paragraph(
        "Proof of Value \u2014 software supply chain assessment", cover_sub))
    lines = [r.customer]
    if r.meta.get("pov_start") and r.meta.get("pov_end"):
        lines.append(str(r.meta["pov_start"]) + " to " + str(r.meta["pov_end"]))
    if r.meta.get("prepared_by"):
        lines.append("Prepared by " + str(r.meta["prepared_by"]))
    for line in lines:
        story.append(Paragraph(esc(line), cover_info))
    story.append(PageBreak())

    # ---------------------------------------------------- executive summary
    story.append(Paragraph("Executive summary", h1))
    para("What the platform found across the estate during this Proof of Value.",
         lede_st)
    if n.get("headline"):
        para(n["headline"], headline_st)
    if n.get("executive_summary"):
        para(n["executive_summary"])
    else:
        para("[[TO BE PROVIDED: executive summary]] \u2014 the figures below were "
             "collected from the tenant, but no narrative was supplied.")

    table(["Metric", "Value"],
          [["Endpoints covered", r.num("devices_total")],
           ["Active endpoints", r.num("devices_active")],
           ["Items discovered", r.num("items_total")],
           ["Unique publishers", r.num("unique_publishers")],
           ["High and critical risk", r.high_and_critical],
           ["Ungoverned high risk", r.num("ungoverned_high_risk")],
           ["Policies enabled", r.num("policies_enabled")],
           ["Remediations recorded", r.num("remediations_total")],
           ["Alerts raised", r.num("alerts_total")],
           ["Agent sessions observed", r.num("agent_sessions_total")]],
          weights=[3, 1])

    stage = r.stage
    if stage:
        para("Tenant lifecycle stage: " + stage + ". "
             + ("The tenant is running in observation mode: nothing is currently "
                "blocked, allowlisted or automatically remediated."
                if stage == "discovery"
                else "Policies and remediation are active in this tenant."))
    else:
        para("Tenant lifecycle stage could not be determined: the governance "
             "domains were not all collected during this PoV.")
    if r.missing:
        para("Not collected during this PoV: " + ", ".join(sorted(r.missing))
             + ". Figures for these areas are absent, not zero, and appear as "
             + NOT_MEASURED + " throughout.", note_st)

    story.append(Paragraph("How this data was collected", h2))
    para("Every figure in this report is read from the customer's Koi tenant "
         "through its API. Endpoint inventory is gathered by a script the "
         "tenant's existing EDR or MDM runs periodically, so no additional "
         "agent was deployed. Risk scores come from the Koi risk engine.")
    para("The analytical sections that follow were written from that collected "
         "data. Every claim cites the specific items it rests on, and those "
         "citations were verified against the collected data before this "
         "report was generated; claims that could not be traced were removed.")

    # ------------------------------------------------------ success criteria
    story.append(PageBreak())
    story.append(Paragraph("Success criteria", h1))
    para("What was agreed at kickoff, and what the collected data shows.", lede_st)
    criteria = n.get("success_criteria") or []
    if criteria:
        table(["Criterion", "Verdict", "Evidence"],
              [[c.get("criterion", ""), str(c.get("verdict", "")).capitalize(),
                c.get("evidence", "")] for c in criteria],
              weights=[4, 1.4, 4], colour_col=1, palette=VERDICT_COLOUR)
    else:
        para("[[TO BE PROVIDED: success criteria agreed at kickoff]] \u2014 none "
             "were supplied, so no verdict can be recorded here.")

    # ------------------------------------------------------------ discovery
    story.append(PageBreak())
    story.append(Paragraph("Discovery", h1))
    para("What is actually installed across the estate.", lede_st)
    views = r.get("items_by_view")
    if views:
        story.append(Paragraph("By category", h2))
        table(["Category", "Items"],
              [[k, format(v, ",")] for k, v in list(views.items())[:12]],
              weights=[3, 1])
    markets = r.get("items_by_marketplace")
    if markets:
        story.append(Paragraph("By marketplace", h2))
        table(["Marketplace", "Items"],
              [[k, format(v, ",")] for k, v in list(markets.items())[:12]],
              weights=[3, 1])
    risk = r.get("items_by_risk")
    if risk:
        story.append(Paragraph("Risk distribution", h2))
        table(["Level", "Items"],
              [[lvl.capitalize(), format(risk[lvl], ",")]
               for lvl in ("critical", "high", "medium", "low", "pending")
               if lvl in risk],
              weights=[3, 1], colour_col=0)
        if risk.get("pending"):
            para(format(risk["pending"], ",") + " items are still awaiting risk "
                 "analysis. Their eventual scores are not reflected above.",
                 note_st)

    # --------------------------------------------------------- supply chain
    pdf_sections.supply_chain(kit, n.get("supply_chain") or {})

    # -------------------------------------------------------- risk inventory
    top = r.rows("top_risk_items")
    if top:
        story.append(PageBreak())
        story.append(Paragraph("Highest-risk items", h1))
        para("Scored by the Koi risk engine, ordered by score.", lede_st)
        rows = []
        for item in top[:20]:
            score = item.get("risk")
            rows.append([
                (item.get("name") or "")[:44],
                (item.get("publisher") or "")[:24],
                item.get("marketplace") or "",
                (item.get("risk_level") or "").capitalize(),
                format(score, ".1f") if isinstance(score, (int, float)) else "\u2014",
                format(int(item.get("endpoints") or 0), ","),
            ])
        table(["Item", "Publisher", "Marketplace", "Risk", "Score", "Endpoints"],
              rows, weights=[3.4, 2.1, 1.9, 1.1, 0.9, 1.1], colour_col=3)

    action = r.rows("action_candidates")
    if action:
        story.append(Paragraph("Ungoverned high-risk items", h2))
        para("High or critical items that no policy currently governs, ordered "
             "by installed footprint.", lede_st)
        table(["Item", "Marketplace", "Risk", "Endpoints", "Findings"],
              [[(i.get("name") or "")[:38], i.get("marketplace") or "",
                (i.get("risk_level") or "").capitalize(),
                format(int(i.get("endpoints") or 0), ","),
                ", ".join((i.get("findings") or [])[:3])[:52]]
               for i in action[:15]],
              weights=[3, 1.8, 1, 1, 3.2], colour_col=2)

    # ------------------------------------------------ findings and scenarios
    pdf_sections.findings(kit, n.get("key_findings") or [])
    pdf_sections.scenarios(kit, n.get("attack_scenarios") or [])

    # ------------------------------------------------------- threat intel
    enr = r.enrichment
    if enr:
        story.append(PageBreak())
        story.append(Paragraph("Threat intelligence", h1))
        fetched = (enr.get("fetched_at") or "")[:10]
        para("Threat intel as of " + (fetched or "unknown date")
             + ". Read exploitation first: KEV membership, then EPSS "
             "probability, then CVSS severity.", lede_st)
        ti = r.ti_rows(20)
        if ti:
            story.append(Paragraph("CVEs in scope", h2))
            table(["CVE", "Known exploited", "EPSS", "CVSS", "Severity"], ti,
                  weights=[2.2, 1.4, 1, 0.9, 1.3], colour_col=4)
            if not r.kev_count:
                para("No CVE in scope appears in the CISA Known Exploited "
                     "Vulnerabilities catalogue, so none is currently evidenced "
                     "as exploited in the wild. That is a statement about "
                     "available evidence, not a guarantee of safety.")
        osv = r.osv_rows(20)
        if osv:
            story.append(Paragraph("Vulnerable packages", h2))
            para("Matched by exact name and installed version against OSV.dev.",
                 lede_st)
            table(["Package", "Advisories", "Identifiers"], osv,
                  weights=[3, 1, 3])
        mitre = r.mitre_rows(20)
        if mitre:
            story.append(Paragraph("ATT&amp;CK techniques from findings", h2))
            para("Mapped from Koi finding types through a curated mapping; "
                 "findings with no mapping are omitted rather than guessed.",
                 lede_st)
            table(["Finding", "Technique", "Name"], mitre, weights=[3, 1.5, 2.5])
        unmapped = enr.get("unmapped_findings") or []
        if unmapped:
            para(str(len(unmapped)) + " finding types have no ATT&CK mapping yet "
                 "and are therefore absent from the table above.", note_st)

    # ------------------------------------------------------------ governance
    story.append(PageBreak())
    story.append(Paragraph("Governance", h1))
    para("Policies, guardrails and lists configured during the PoV.", lede_st)
    policies = r.rows("policies")
    if policies:
        story.append(Paragraph("Marketplace policies", h2))
        table(["Policy", "Action", "State", "Groups"],
              [[(p.get("name") or "")[:44], (p.get("action") or "").capitalize(),
                "Enabled" if p.get("enabled") else "Disabled",
                str(p.get("groups")) if p.get("groups") else "All"]
               for p in policies[:20]],
              weights=[4, 1.2, 1.2, 1])
    runtime = r.rows("runtime_policies")
    if runtime:
        story.append(Paragraph("Agent runtime policies", h2))
        table(["Policy", "Mode", "Agents", "Rule types"],
              [[(p.get("name") or "")[:40], (p.get("mode") or "").capitalize(),
                ", ".join(p.get("agents") or [])[:30] or "\u2014",
                ", ".join(sorted(set(p.get("rule_types") or [])))[:30] or "\u2014"]
               for p in runtime[:15]],
              weights=[3, 1, 2, 2])
    approvals = r.mapping("approvals_by_status")
    story.append(Paragraph("Lists and approvals", h2))
    table(["Control", "Count"],
          [["Items allowlisted", r.num("allowlist_count")],
           ["Items blocklisted", r.num("blocklist_count")],
           ["Approvals approved", format(int(approvals.get("approved", 0)), ",")],
           ["Approvals pending", format(int(approvals.get("pending", 0)), ",")]],
          weights=[3, 1])

    # ----------------------------------------------------------- remediation
    story.append(PageBreak())
    story.append(Paragraph("Remediation", h1))
    para("Risk actually removed from endpoints during the PoV.", lede_st)
    by_status = r.get("remediations_by_status")
    if by_status:
        table(["Status", "Count"],
              [[str(k).capitalize(), format(v, ",")] for k, v in by_status.items()],
              weights=[3, 1])
    elif not r.measured("remediations_total"):
        para("Remediation data was " + NOT_MEASURED + ".")
    remediated = r.rows("remediated_items")
    if remediated:
        story.append(Paragraph("Items removed from endpoints", h2))
        table(["Item", "Endpoint", "Platform", "Risk", "Reason"],
              [[(i.get("name") or "")[:38], (i.get("hostname") or "")[:22],
                i.get("platform") or "", (i.get("risk_level") or "").capitalize(),
                (i.get("reason") or "")[:30]]
               for i in remediated[:20]],
              weights=[3, 2, 1.2, 1, 2.4], colour_col=3)
    alerts = r.get("alerts_by_severity")
    if alerts:
        story.append(Paragraph("Alerts raised", h2))
        table(["Severity", "Count"],
              [[str(k).capitalize(), format(v, ",")] for k, v in alerts.items()],
              weights=[3, 1], colour_col=0)

    # -------------------------------------------------------------- agentic
    story.append(PageBreak())
    story.append(Paragraph("Agentic runtime activity", h1))
    para("Coding-agent sessions observed and governed on managed endpoints.",
         lede_st)
    decisions = r.get("agent_decisions")
    if decisions:
        table(["Decision", "Actions"],
              [[str(k).capitalize(), format(v, ",")] for k, v in decisions.items()],
              weights=[3, 1])
    agents = r.get("agents_seen")
    if agents:
        story.append(Paragraph("Agents in use", h2))
        table(["Agent", "Sessions"],
              [[k, format(v, ",")] for k, v in list(agents.items())[:10]],
              weights=[3, 1])
    blocked = r.rows("agent_blocked_examples")
    if blocked:
        story.append(Paragraph("Blocked actions", h2))
        para("Sample from the last 24 hours; the API caps the event window.",
             lede_st)
        table(["Agent", "Endpoint", "Action", "Target"],
              [[b.get("agent") or "", (b.get("host") or "")[:22],
                (b.get("action") or "")[:18], (b.get("target") or "")[:44]]
               for b in blocked[:15]],
              weights=[1.4, 2, 1.4, 3.4])
    if not r.measured("agent_sessions_total"):
        para("Agent activity was " + NOT_MEASURED + " during this PoV.")

    # ------------------------------------------------------ xsiam correlation
    x = r.xsiam
    if x:
        story.append(PageBreak())
        story.append(Paragraph("Cortex XSIAM correlation", h1))
        para("Where third-party exposure meets detections raised on the same "
             "estate.", lede_st)
        cov = x.get("coverage") or {}
        inc = x.get("incidents") or {}
        table(["Metric", "Value"],
              [["Endpoints known to Koi", format(int(cov.get("koi_devices", 0)), ",")],
               ["Endpoints known to XSIAM",
                format(int(cov.get("xsiam_endpoints", 0)), ",")],
               ["Present in both", format(int(cov.get("on_both", 0)), ",")],
               ["Koi only", format(int(cov.get("koi_only_count", 0)), ",")],
               ["XSIAM only", format(int(cov.get("xsiam_only_count", 0)), ",")],
               ["XSIAM incidents in window", format(int(inc.get("total", 0)), ",")]],
              weights=[3, 1])
        para("Correlation here means co-occurrence: the same host appearing in "
             "both platforms. It does not establish that discovered software "
             "caused a detection, and this report never claims that it did.")
        hosts = inc.get("top_koi_hosts") or []
        if hosts:
            story.append(Paragraph("Koi-known endpoints carrying incidents", h2))
            table(["Endpoint", "Incidents"],
                  [[h.get("host", ""), format(int(h.get("incidents", 0)), ",")]
                   for h in hosts[:20]],
                  weights=[3, 1])

    # ---------------------------------------- actions and threat context
    pdf_sections.actions(kit, n.get("recommended_actions") or [],
                         fallback=n.get("recommendations") or "")
    pdf_sections.threat_context(kit, n.get("threat_context") or [])

    # -------------------------------------------------------------- appendix
    story.append(PageBreak())
    story.append(Paragraph("Appendix", h1))
    freq = r.rows("finding_frequency")
    if freq:
        story.append(Paragraph("Most frequent findings", h2))
        table(["Finding", "Occurrences"],
              [[str(f.get("finding")).replace("_", " "),
                format(int(f.get("count") or 0), ",")] for f in freq[:15]],
              weights=[4, 1])

    pdf_sections.data_gaps(kit, n.get("data_gaps") or [])

    if r.missing:
        story.append(Paragraph("Domains not collected", h2))
        para(", ".join(sorted(r.missing)))
        para("Figures depending on these domains are absent, not zero.", note_st)
    warnings = r.raw("warnings", []) or []
    if warnings:
        story.append(Paragraph("Collection warnings", h2))
        for w in warnings[:15]:
            para("\u2022 " + str(w))
    story.append(Paragraph("About this report", h2))
    para("Generated by koi-pov-mcp. Figures are read from the customer's Koi "
         "tenant at the time of collection. Narrative sections are written by "
         "the consultant from that same data; anything left unwritten appears "
         "as a visible placeholder rather than being invented.", note_st)
    pdf_sections.validation_note(kit, n.get("validation"))

    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    doc.build(story)
    log.info("PDF written to %s", out_path)
    return out_path
